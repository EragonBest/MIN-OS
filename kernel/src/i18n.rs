impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::It => "it",
            Lang::En => "en",
            Lang::Es => "es",
            Lang::Fr => "fr",
            Lang::De => "de",
        }
    }
    pub fn tr(self) -> &'static Tr {
        match self {
            Lang::It => &IT,
            Lang::En => &EN,
            Lang::Es => &ES,
            Lang::Fr => &FR,
            Lang::De => &DE,
        }
    }
}

